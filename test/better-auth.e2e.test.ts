import { betterAuth } from 'better-auth'
import { getAuthTables } from 'better-auth/db'
import { afterAll, beforeAll, describe, expect, it } from 'vitest'

import { createTestSchema, createTestSql, dropTestSchema } from './+helpers.ts'
import { postgresJsAdapter } from '../src/index.ts'

const schemaName = 'adapter_e2e_test'

const sql = createTestSql()

const database = postgresJsAdapter(sql, { schema: schemaName, casing: 'snake_case' })

const authOptions = {
  database,
  baseURL: 'http://localhost:3000',
  secret: '01234567890123456789012345678901',
  emailAndPassword: { enabled: true },
  user: { deleteUser: { enabled: true } },
  rateLimit: { enabled: false },
}

const auth = betterAuth(authOptions)

async function countRows(table: string): Promise<number> {
  const rows =
    await sql`SELECT COUNT(*)::int AS count FROM ${sql(schemaName)}.${sql(table)}`
  return Number(rows[0].count)
}

// Runs before the block below, whose cleanup closes the shared client.
describe('better auth rate limiting stored in postgres', () => {
  const rateLimitSchema = 'adapter_rate_limit_test'
  const rateLimitDatabase = postgresJsAdapter(sql, { schema: rateLimitSchema })
  const rateLimitOptions = {
    database: rateLimitDatabase,
    baseURL: 'http://localhost:3000',
    secret: '01234567890123456789012345678901',
    rateLimit: { enabled: true, storage: 'database' as const },
  }

  beforeAll(async () => {
    await createTestSchema(sql, rateLimitSchema)
    const generated =
      await rateLimitDatabase(rateLimitOptions).createSchema?.(rateLimitOptions)
    await sql.unsafe(generated?.code ?? '')
  })

  afterAll(async () => {
    await sql.unsafe(`DROP SCHEMA IF EXISTS "${rateLimitSchema}" CASCADE`)
  })

  it('records a millisecond timestamp above the 32-bit range for a handled request', async () => {
    const res = await betterAuth(rateLimitOptions).handler(
      new Request('http://localhost:3000/api/auth/ok', {
        headers: { 'x-forwarded-for': '203.0.113.7' },
      }),
    )
    expect(res.status).toBe(200)

    const rows = await sql`
      SELECT "lastRequest" FROM ${sql(rateLimitSchema)}."rateLimit"
    `
    expect(rows).toHaveLength(1)
    expect(Number(rows[0].lastRequest)).toBeGreaterThan(2 ** 31)
  })
})

// Tests share one user and run in order; each depends on the state left by the previous.
describe('better auth end-to-end with postgres', () => {
  beforeAll(async () => {
    await createTestSchema(sql, schemaName)

    // Schema generated by the adapter itself from Better Auth's table definitions.
    const adapter = database(authOptions)
    const tables = getAuthTables(authOptions)
    const generated = await adapter.createSchema?.(tables)
    expect(generated?.code).toContain('CREATE TABLE')
    await sql.unsafe(generated?.code ?? '')
  })

  afterAll(async () => {
    await dropTestSchema(sql, schemaName)
  })

  const email = 'e2e@example.com'
  const password = 'correct-horse-battery'
  let token = ''

  it('signs up a user and persists user and account rows', async () => {
    const res = await auth.api.signUpEmail({
      body: { name: 'E2E User', email, password },
    })

    expect(res.user.email).toBe(email)
    expect(await countRows('user')).toBe(1)
    expect(await countRows('account')).toBe(1)

    const accounts = await sql`
      SELECT * FROM ${sql(schemaName)}.${sql('account')} WHERE user_id = ${res.user.id}
    `
    expect(accounts[0].provider_id).toBe('credential')
    // Password must be hashed, never stored in plaintext.
    expect(accounts[0].password).not.toBe(password)
  })

  it('rejects duplicate sign up', async () => {
    await expect(
      auth.api.signUpEmail({ body: { name: 'Dup', email, password } }),
    ).rejects.toThrow()
    expect(await countRows('user')).toBe(1)
  })

  it('signs in and creates a session', async () => {
    const res = await auth.api.signInEmail({ body: { email, password } })
    token = res.token
    expect(token).toBeTruthy()
    expect(await countRows('session')).toBeGreaterThanOrEqual(1)
  })

  it('rejects a wrong password', async () => {
    await expect(
      auth.api.signInEmail({ body: { email, password: 'wrong-password-123' } }),
    ).rejects.toThrow()
  })

  it('resolves the session via getSession', async () => {
    const headers = new Headers({ authorization: `Bearer ${token}` })
    const signed = await auth.api.signInEmail({
      body: { email, password },
      returnHeaders: true,
    })
    const cookie = signed.headers
      .getSetCookie()
      .map((c) => c.split(';')[0])
      .join('; ')
    headers.set('cookie', cookie)

    const session = await auth.api.getSession({ headers })
    expect(session?.user.email).toBe(email)
    expect(session?.session.userId).toBe(session?.user.id)
  })

  it('updates the user through the api', async () => {
    const signed = await auth.api.signInEmail({
      body: { email, password },
      returnHeaders: true,
    })
    const cookie = signed.headers
      .getSetCookie()
      .map((c) => c.split(';')[0])
      .join('; ')

    await auth.api.updateUser({
      body: { name: 'Renamed' },
      headers: new Headers({ cookie }),
    })

    const rows = await sql`
      SELECT name FROM ${sql(schemaName)}.${sql('user')} WHERE email = ${email}
    `
    expect(rows[0].name).toBe('Renamed')
  })

  it('signs out and removes the session row', async () => {
    const signed = await auth.api.signInEmail({
      body: { email, password },
      returnHeaders: true,
    })
    const cookie = signed.headers
      .getSetCookie()
      .map((c) => c.split(';')[0])
      .join('; ')
    const before = await countRows('session')

    await auth.api.signOut({ headers: new Headers({ cookie }) })

    expect(await countRows('session')).toBe(before - 1)
    const session = await auth.api.getSession({ headers: new Headers({ cookie }) })
    expect(session).toBeNull()
  })

  it('deletes a user and cascades through the adapter', async () => {
    const signed = await auth.api.signInEmail({
      body: { email, password },
      returnHeaders: true,
    })
    const cookie = signed.headers
      .getSetCookie()
      .map((c) => c.split(';')[0])
      .join('; ')

    expect(await countRows('user')).toBe(1)
    expect(await countRows('account')).toBeGreaterThanOrEqual(1)
    expect(await countRows('session')).toBeGreaterThanOrEqual(1)

    await auth.api.deleteUser({
      body: { password },
      headers: new Headers({ cookie }),
    })
    expect(await countRows('user')).toBe(0)
    expect(await countRows('account')).toBe(0)
    expect(await countRows('session')).toBe(0)
  })
})
